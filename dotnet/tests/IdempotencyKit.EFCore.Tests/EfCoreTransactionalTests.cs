namespace IdempotencyKit.EFCore.Tests;

public sealed class EfOrder
{
    public long Id { get; set; }
    public string ScopeKeyHash { get; set; } = "";
    public int Quantity { get; set; }
}

public sealed class OrdersContext(DbContextOptions<OrdersContext> options) : DbContext(options)
{
    public DbSet<EfOrder> Orders => Set<EfOrder>();

    protected override void OnModelCreating(ModelBuilder model)
    {
        model.Entity<EfOrder>(entity =>
        {
            entity.ToTable("idempotencykit_ef_orders_test");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Id).HasColumnName("id").ValueGeneratedOnAdd();
            entity.Property(x => x.ScopeKeyHash).HasColumnName("scope_key_hash").IsRequired();
            entity.Property(x => x.Quantity).HasColumnName("quantity");
        });
    }
}

public sealed class EfCoreFixture : IAsyncLifetime
{
    public NpgsqlDataSource DataSource { get; private set; } = null!;

    public async Task InitializeAsync()
    {
        var url = Environment.GetEnvironmentVariable("IDEMPOTENCYKIT_TEST_POSTGRES")
            ?? throw new InvalidOperationException("PostgreSQL integration database required.");
        DataSource = NpgsqlDataSource.Create(url);
        await using var connection = await DataSource.OpenConnectionAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        await using (var advisory = new NpgsqlCommand(
            "SELECT pg_advisory_xact_lock(hashtext('idempotencykit_schema_001'))",
            connection, transaction))
            await advisory.ExecuteNonQueryAsync();

        string? migration = null;
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory);
             dir is not null; dir = dir.Parent)
        {
            var file = Path.Combine(dir.FullName, "spec", "sql", "postgres",
                "001_idempotencykit_records.sql");
            if (File.Exists(file)) { migration = file; break; }
        }
        if (migration is null) throw new FileNotFoundException("Shared SQL migration not found.");

        await using (var sql = new NpgsqlCommand(File.ReadAllText(migration),
            connection, transaction))
            await sql.ExecuteNonQueryAsync();

        await using (var sql = new NpgsqlCommand("""
            CREATE TABLE IF NOT EXISTS idempotencykit_ef_orders_test (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                scope_key_hash text NOT NULL,
                quantity integer NOT NULL
            )
            """, connection, transaction))
            await sql.ExecuteNonQueryAsync();

        await transaction.CommitAsync();
    }

    public async Task DisposeAsync() => await DataSource.DisposeAsync();
}

public sealed class EfCoreTransactionalTests(EfCoreFixture fixture)
    : IClassFixture<EfCoreFixture>
{
    private static string NewKey() => RequestIdentityHasher.ComputeScopeKey(
        new IdempotencyRequestScope("efcore-test", "orders.create.v1",
            "user-" + Guid.NewGuid().ToString("N"),
            "key-" + Guid.NewGuid().ToString("N"), "tenant-a"));

    private static string Fingerprint(int quantity) => RequestFingerprinter.Compute(
        new RequestFingerprintInput("POST", "orders.create.v1", "/orders",
            BodyJson: $"{{\"quantity\":{quantity}}}"));

    private PostgresEfCoreTransactionalExecutor<OrdersContext> CreateExecutor(
        Func<NpgsqlConnection, OrdersContext>? factory = null)
    {
        factory ??= connection => new OrdersContext(
            new DbContextOptionsBuilder<OrdersContext>()
                .UseNpgsql(connection).Options);

        return new PostgresEfCoreTransactionalExecutor<OrdersContext>(
            new PostgresTransactionalExecutor(fixture.DataSource), factory);
    }

    private static StoredHttpResponse Response(long id, int quantity) => new(
        201, "application/json",
        Encoding.UTF8.GetBytes($"{{\"id\":{id},\"quantity\":{quantity}}}"),
        new Dictionary<string, string> { ["Location"] = "/orders/" + id });

    private async Task<long> CountOrders(string key)
    {
        await using var connection = await fixture.DataSource.OpenConnectionAsync();
        await using var command = new NpgsqlCommand(
            "SELECT count(*) FROM idempotencykit_ef_orders_test WHERE scope_key_hash = @key",
            connection);
        command.Parameters.AddWithValue("key", key);
        return (long)(await command.ExecuteScalarAsync())!;
    }

    private async Task<long> CountRecords(string key)
    {
        await using var connection = await fixture.DataSource.OpenConnectionAsync();
        await using var command = new NpgsqlCommand(
            "SELECT count(*) FROM idempotencykit_records WHERE scope_key_hash = @key",
            connection);
        command.Parameters.AddWithValue("key", key);
        return (long)(await command.ExecuteScalarAsync())!;
    }

    [Fact]
    public async Task EfContextAndIdempotencyResponseCommitTogetherThenReplay()
    {
        var key = NewKey();
        var hash = Fingerprint(2);
        int callbacks = 0;
        var first = await CreateExecutor().ExecuteAsync(key, hash,
            async (context, ct) =>
            {
                Interlocked.Increment(ref callbacks);
                var order = new EfOrder { ScopeKeyHash = key, Quantity = 2 };
                context.Orders.Add(order);
                await context.SaveChangesAsync(ct);
                return Response(order.Id, 2);
            }, TimeSpan.FromMinutes(5));

        Assert.Equal(TransactionalIdempotencyStatus.Executed, first.Status);
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));

        var again = await CreateExecutor().ExecuteAsync(key, hash,
            (context, ct) =>
                throw new InvalidOperationException("Replay cannot run EF callback."),
            TimeSpan.FromMinutes(5));
        Assert.Equal(TransactionalIdempotencyStatus.Replayed, again.Status);
        Assert.Equal(first.Response!.Body, again.Response!.Body);
        Assert.Equal(first.Response.Headers["location"], again.Response.Headers["location"]);
        Assert.Equal(1, callbacks);

        var mismatch = await CreateExecutor().ExecuteAsync(key, Fingerprint(3),
            (context, ct) => throw new InvalidOperationException(
                "Different body must never execute EF callback."),
            TimeSpan.FromMinutes(5));
        Assert.Equal(TransactionalIdempotencyStatus.FingerprintMismatch, mismatch.Status);
        Assert.Equal(1L, await CountOrders(key));
    }

    [Fact]
    public async Task EfSaveChangesFollowedByExceptionRollsBackBothTables()
    {
        var key = NewKey();
        var hash = Fingerprint(4);
        await Assert.ThrowsAsync<InvalidOperationException>(() =>
            CreateExecutor().ExecuteAsync(key, hash,
                async (context, ct) =>
                {
                    context.Orders.Add(new EfOrder { ScopeKeyHash = key, Quantity = 4 });
                    await context.SaveChangesAsync(ct);
                    throw new InvalidOperationException("Abort after EF SaveChanges.");
                }, TimeSpan.FromMinutes(5)));

        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));
    }

    [Fact]
    public async Task RemainingTrackedChangesAutoSaveBeforeCommit()
    {
        var key = NewKey();
        var result = await CreateExecutor().ExecuteAsync(key, Fingerprint(5),
            (context, ct) =>
            {
                context.Orders.Add(new EfOrder { ScopeKeyHash = key, Quantity = 5 });
                return Task.FromResult(Response(0, 5));
            }, TimeSpan.FromMinutes(5));
        Assert.Equal(TransactionalIdempotencyStatus.Executed, result.Status);
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));
    }

    [Fact]
    public async Task FactoryUsingDifferentConnectionFailsClosed()
    {
        var key = NewKey();
        var bad = CreateExecutor(_ => new OrdersContext(
            new DbContextOptionsBuilder<OrdersContext>()
                .UseNpgsql(fixture.DataSource.ConnectionString).Options));

        await Assert.ThrowsAsync<InvalidOperationException>(() => bad.ExecuteAsync(
            key, Fingerprint(6), (ctx, ct) =>
            {
                ctx.Orders.Add(new EfOrder { ScopeKeyHash = key, Quantity = 6 });
                return Task.FromResult(Response(0, 6));
            }, TimeSpan.FromMinutes(5)));

        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));
    }

    [Fact]
    public async Task TwelveConcurrentEfCallbacksCommitOnlyOneOrder()
    {
        var key = NewKey();
        var hash = Fingerprint(7);
        int callbacks = 0;
        var executor = CreateExecutor();
        var attempts = await Task.WhenAll(Enumerable.Range(0, 12).Select(_ =>
            executor.ExecuteAsync(key, hash, async (context, ct) =>
            {
                Interlocked.Increment(ref callbacks);
                var order = new EfOrder { ScopeKeyHash = key, Quantity = 7 };
                context.Orders.Add(order);
                await context.SaveChangesAsync(ct);
                return Response(order.Id, 7);
            }, TimeSpan.FromMinutes(5))));

        Assert.Single(attempts, x => x.Status == TransactionalIdempotencyStatus.Executed);
        Assert.Equal(1, callbacks);
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));
        Assert.All(attempts, x => Assert.Contains(x.Status,
            new[] { TransactionalIdempotencyStatus.Executed,
                TransactionalIdempotencyStatus.Replayed,
                TransactionalIdempotencyStatus.InProgress }));
    }
}
