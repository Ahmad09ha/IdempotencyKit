using System.Text;
using IdempotencyKit.Core;
using IdempotencyKit.Postgres;
using Npgsql;
using Xunit;

namespace IdempotencyKit.Postgres.Tests;

/// <summary>
/// Real PostgreSQL tests: the business order and completed replay record must
/// share ONE transaction, including concurrency and interrupted transactions.
/// </summary>
public sealed class PostgresTransactionalTests(PostgresFixture fixture)
    : IClassFixture<PostgresFixture>
{
    private static string NewKey() => RequestIdentityHasher.ComputeScopeKey(
        new IdempotencyRequestScope("transaction-test", "orders.create.v1",
            "user-" + Guid.NewGuid().ToString("N"),
            "order-" + Guid.NewGuid().ToString("N"), "tenant-a"));

    private static string Fingerprint(int quantity) => RequestFingerprinter.Compute(
        new RequestFingerprintInput("POST", "orders.create.v1",
            "/orders", BodyJson: $"{{\"quantity\":{quantity}}}"));

    private static StoredHttpResponse Json(int id, int quantity) =>
        new(201, "application/json; charset=utf-8",
            Encoding.UTF8.GetBytes($"{{\"id\":{id},\"quantity\":{quantity}}}"),
            new Dictionary<string, string> { ["Location"] = "/orders/" + id });

    private async Task EnsureOrdersTableAsync()
    {
        await using var connection = await fixture.DataSource.OpenConnectionAsync();
        await using var transaction = await connection.BeginTransactionAsync();
        await using (var advisory = new NpgsqlCommand(
            "SELECT pg_advisory_xact_lock(hashtext('idempotencykit_txn_orders_test'))",
            connection, transaction))
            await advisory.ExecuteNonQueryAsync();

        await using (var command = new NpgsqlCommand("""
            CREATE TABLE IF NOT EXISTS idempotencykit_txn_orders_test (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                scope_key_hash text NOT NULL,
                quantity integer NOT NULL
            )
            """, connection, transaction))
            await command.ExecuteNonQueryAsync();
        await transaction.CommitAsync();
    }

    private static async Task<StoredHttpResponse> InsertOrder(
        NpgsqlConnection connection, NpgsqlTransaction transaction,
        CancellationToken cancellationToken, string key, int quantity)
    {
        await using var command = new NpgsqlCommand("""
            INSERT INTO idempotencykit_txn_orders_test(scope_key_hash, quantity)
            VALUES (@key, @quantity) RETURNING id
            """, connection, transaction);
        command.Parameters.AddWithValue("key", key);
        command.Parameters.AddWithValue("quantity", quantity);
        var id = (long)(await command.ExecuteScalarAsync(cancellationToken))!;
        return Json(checked((int)id), quantity);
    }

    private async Task<long> CountOrders(string key)
    {
        await using var conn = await fixture.DataSource.OpenConnectionAsync();
        await using var cmd = new NpgsqlCommand("""
            SELECT count(*) FROM idempotencykit_txn_orders_test
             WHERE scope_key_hash = @key
            """, conn);
        cmd.Parameters.AddWithValue("key", key);
        return (long)(await cmd.ExecuteScalarAsync())!;
    }

    private async Task<long> CountRecords(string key)
    {
        await using var conn = await fixture.DataSource.OpenConnectionAsync();
        await using var cmd = new NpgsqlCommand("""
            SELECT count(*) FROM idempotencykit_records
             WHERE scope_key_hash = @key
            """, conn);
        cmd.Parameters.AddWithValue("key", key);
        return (long)(await cmd.ExecuteScalarAsync())!;
    }

    [Fact]
    public async Task OneCommitCreatesOrderAndReplayRecord_ThenRetryDoesNotCallCallback()
    {
        await EnsureOrdersTableAsync();
        var executor = new PostgresTransactionalExecutor(fixture.DataSource);
        string key = NewKey(), hash = Fingerprint(2);
        int calls = 0;

        var original = await executor.ExecuteAsync(
            key, hash, async (conn, tx, ct) =>
            {
                Interlocked.Increment(ref calls);
                return await InsertOrder(conn, tx, ct, key, 2);
            }, TimeSpan.FromHours(2));

        Assert.Equal(TransactionalIdempotencyStatus.Executed, original.Status);
        Assert.Equal(1, calls);
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));

        var replica = new PostgresTransactionalExecutor(fixture.DataSource);
        var repeated = await replica.ExecuteAsync(
            key, hash, (conn, tx, ct) =>
            {
                Interlocked.Increment(ref calls);
                throw new InvalidOperationException("Replayed callback must not run.");
            }, TimeSpan.FromHours(2));

        Assert.Equal(TransactionalIdempotencyStatus.Replayed, repeated.Status);
        Assert.Equal(original.Response!.StatusCode, repeated.Response!.StatusCode);
        Assert.Equal(original.Response.Body, repeated.Response.Body);
        Assert.Equal(original.Response.Headers["location"], repeated.Response.Headers["location"]);
        Assert.Equal(1, calls);
        Assert.Equal(1L, await CountOrders(key));

        var mismatch = await replica.ExecuteAsync(
            key, Fingerprint(3), (conn, tx, ct) =>
                throw new InvalidOperationException("Mismatched callback must not run."),
            TimeSpan.FromHours(2));
        Assert.Equal(TransactionalIdempotencyStatus.FingerprintMismatch, mismatch.Status);
        Assert.Equal(1L, await CountOrders(key));
    }

    [Fact]
    public async Task CallbackThrowsAfterInsertingOrder_BothWritesRollback()
    {
        await EnsureOrdersTableAsync();
        var executor = new PostgresTransactionalExecutor(fixture.DataSource);
        string key = NewKey(), hash = Fingerprint(4);
        await Assert.ThrowsAsync<InvalidOperationException>(() => executor.ExecuteAsync(
            key, hash, async (conn, tx, ct) =>
            {
                await InsertOrder(conn, tx, ct, key, 4);
                throw new InvalidOperationException("Simulated business failure");
            }, TimeSpan.FromHours(1)));

        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));

        var retry = await executor.ExecuteAsync(
            key, hash, (conn, tx, ct) => InsertOrder(conn, tx, ct, key, 4),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.Executed, retry.Status);
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));
    }

    [Fact]
    public async Task ResponseValidationFails_BusinessWriteRollsBack()
    {
        await EnsureOrdersTableAsync();
        var executor = new PostgresTransactionalExecutor(fixture.DataSource);
        string key = NewKey(), hash = Fingerprint(5);
        await Assert.ThrowsAnyAsync<Exception>(() => executor.ExecuteAsync(
            key, hash, async (conn, tx, ct) =>
            {
                var response = await InsertOrder(conn, tx, ct, key, 5);
                return response with
                {
                    Headers = new Dictionary<string, string> {
                        ["Set-Cookie"] = "secret=yes"
                    }
                };
            }, TimeSpan.FromHours(1)));
        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));

        await Assert.ThrowsAnyAsync<Exception>(() => executor.ExecuteAsync(
            key, hash, async (conn, tx, ct) =>
            {
                var response = await InsertOrder(conn, tx, ct, key, 5);
                return response with { Body = Encoding.UTF8.GetBytes("not-json") };
            }, TimeSpan.FromHours(1)));
        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));
    }

    [Fact]
    public async Task TwentyFourConcurrentAttempts_CommitExactlyOneBusinessOrder()
    {
        await EnsureOrdersTableAsync();
        var executor = new PostgresTransactionalExecutor(
            fixture.DataSource, TimeSpan.FromSeconds(5));
        string key = NewKey(), hash = Fingerprint(6);
        int calls = 0;

        var attempts = await Task.WhenAll(Enumerable.Range(0, 24).Select(_ =>
            executor.ExecuteAsync(
                key, hash, async (conn, tx, ct) =>
                {
                    Interlocked.Increment(ref calls);
                    await Task.Delay(120, ct);
                    return await InsertOrder(conn, tx, ct, key, 6);
                }, TimeSpan.FromHours(1))));

        Assert.Equal(1, calls);
        Assert.Single(attempts, x => x.Status == TransactionalIdempotencyStatus.Executed);
        Assert.All(attempts, result => Assert.Contains(result.Status, new[]
        {
            TransactionalIdempotencyStatus.Executed,
            TransactionalIdempotencyStatus.Replayed,
            TransactionalIdempotencyStatus.InProgress
        }));
        Assert.Equal(1L, await CountOrders(key));
        Assert.Equal(1L, await CountRecords(key));

        var after = await executor.ExecuteAsync(
            key, hash, (conn, tx, ct) =>
                throw new Exception("Completed callback cannot run"),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.Replayed, after.Status);
    }

    [Fact]
    public async Task StandardAndTransactionalModesRespectExistingRecords()
    {
        await EnsureOrdersTableAsync();
        var standard = new PostgresIdempotencyStore(fixture.DataSource);
        var transactional = new PostgresTransactionalExecutor(fixture.DataSource);
        string key = NewKey(), hash = Fingerprint(7);

        var claimed = await standard.TryClaimAsync(key, hash, TimeSpan.FromMinutes(1));
        Assert.Equal(IdempotencyClaimStatus.Acquired, claimed.Status);
        var processing = await transactional.ExecuteAsync(
            key, hash, (conn, tx, ct) =>
                throw new Exception("Cannot run while Standard mode owns the record."),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.InProgress, processing.Status);

        Assert.True(await standard.TryMarkUncertainAsync(
            key, hash, claimed.OwnerToken!.Value));
        var uncertain = await transactional.ExecuteAsync(
            key, hash, (conn, tx, ct) =>
                throw new Exception("Uncertain records must not execute."),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.Uncertain, uncertain.Status);

        string completedKey = NewKey();
        var committed = await transactional.ExecuteAsync(
            completedKey, hash, (conn, tx, ct) =>
                InsertOrder(conn, tx, ct, completedKey, 7),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.Executed, committed.Status);
        var standardReplay = await standard.TryClaimAsync(
            completedKey, hash, TimeSpan.FromMinutes(1));
        Assert.Equal(IdempotencyClaimStatus.Completed, standardReplay.Status);
        Assert.Equal(committed.Response!.Body, standardReplay.Response!.Body);
    }

    [Fact]
    public async Task TerminatingBackendBeforeCommit_RollsBackOrderAndAllowsSameKeyRetry()
    {
        await EnsureOrdersTableAsync();
        var executor = new PostgresTransactionalExecutor(fixture.DataSource);
        string key = NewKey(), hash = Fingerprint(8);

        await Assert.ThrowsAnyAsync<Exception>(() => executor.ExecuteAsync(
            key, hash, async (conn, tx, ct) =>
            {
                await InsertOrder(conn, tx, ct, key, 8);
                await using var cmd = new NpgsqlCommand(
                    "SELECT pg_terminate_backend(pg_backend_pid())", conn, tx);
                await cmd.ExecuteScalarAsync(ct);
                throw new InvalidOperationException("Expected backend termination");
            }, TimeSpan.FromHours(1)));

        Assert.Equal(0L, await CountOrders(key));
        Assert.Equal(0L, await CountRecords(key));

        var retry = await executor.ExecuteAsync(
            key, hash, (conn, tx, ct) =>
                InsertOrder(conn, tx, ct, key, 8),
            TimeSpan.FromHours(1));
        Assert.Equal(TransactionalIdempotencyStatus.Executed, retry.Status);
        Assert.Equal(1L, await CountOrders(key));
    }
}
