async function count(key) {
  const result = await pool.query(
    "SELECT count(*) AS count FROM idempotencykit_nest_http_orders_test WHERE client_key = $1",
    [key]);
  return Number(result.rows[0].count);
}

async function request(path, body, key, user = "alice", tenant = "acme") {
  const headers = {
    "Content-Type": "application/json",
    "X-Test-Tenant": tenant,
  };
  if (user !== null) headers["X-Test-User"] = user;
  if (key !== null) headers["Idempotency-Key"] = key;
  const response = await fetch(base + path, {
    method: "POST", headers, body: JSON.stringify(body),
  });
  const raw = await response.text();
  return {
    status: response.status, body: raw ? JSON.parse(raw) : null,
    raw, location: response.headers.get("location"),
    retryAfter: response.headers.get("retry-after"),
  };
}

integration("committed transactional JSON response replays without another SQL mutation", async () => {
  const key = "tx-http-" + randomUUID();
  const first = await request("/orders/transactional", { itemId: 11, quantity: 2 }, key);
  assert.equal(first.status, 201);
  assert.equal(first.location, "/orders/transactional/" + first.body.id);
  const firstCalls = createCalls;

  const retry = await request("/orders/transactional", { quantity: 2, itemId: 11 }, key);
  assert.equal(retry.status, 201);
  assert.equal(retry.raw, first.raw);
  assert.equal(retry.location, first.location);
  assert.equal(createCalls, firstCalls);
  assert.equal(await count(key), 1);
});

integration("same key with changed request is 422 and missing key is 400", async () => {
  const key = "tx-http-" + randomUUID();
  assert.equal((await request("/orders/transactional", { itemId: 11, quantity: 2 }, key)).status, 201);
  const before = createCalls;
  const mismatch = await request("/orders/transactional", { itemId: 11, quantity: 3 }, key);
  assert.equal(mismatch.status, 422);
  assert.equal(mismatch.body.code, "IDEMPOTENCY_FINGERPRINT_MISMATCH");
  assert.equal((await request("/orders/transactional", { itemId: 11, quantity: 2 }, null)).status, 400);
  assert.equal(createCalls, before);
});

