integration("processing same-key request returns 409 with retry-after, then replays", async () => {
  const key = "tx-http-" + randomUUID();
  const before = slowCalls;
  const first = request("/orders/transactional/slow", { quantity: 8 }, key);
  for (let i = 0; i < 120 && slowCalls === before; i++)
    await new Promise(resolve => setTimeout(resolve, 5));
  assert.equal(slowCalls, before + 1);

  const second = await request("/orders/transactional/slow", { quantity: 8 }, key);
  assert.equal(second.status, 409);
  assert.equal(second.retryAfter, "1");
  assert.equal(second.body.code, "IDEMPOTENCY_IN_PROGRESS");
  assert.equal((await first).status, 201);
  const replay = await request("/orders/transactional/slow", { quantity: 8 }, key);
  assert.equal(replay.status, 201);
  assert.equal(slowCalls, before + 1);
  assert.equal(await count(key), 1);
});

