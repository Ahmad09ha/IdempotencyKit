import test, { before, after } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { fork } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import pg from "pg";
import { computeRequestFingerprint, computeScopeKey } from "@idempotencykit/core";
import {
  PostgresIdempotencyStore, PostgresTransactionalExecutor,
} from "@idempotencykit/postgres";

const url = process.env.IDEMPOTENCYKIT_TEST_POSTGRES_URL;
const pool = url ? new pg.Pool({ connectionString: url, max: 32 }) : null;
// Killing a PostgreSQL backend in a fault-injection test may emit a late pool
// 'error' event after the failed query has already rejected. Capture it so
// Node's test runner does not interpret the expected disconnect as unhandled.
const unexpectedPoolErrors = [];
let allowExpectedBackendTermination = false;
pool?.on("error", error => {
  if (allowExpectedBackendTermination &&
      /connection terminated unexpectedly|terminating connection/i.test(error.message))
    return;
  unexpectedPoolErrors.push(error);
});
const executor = pool ? new PostgresTransactionalExecutor(pool) : null;
const store = pool ? new PostgresIdempotencyStore(pool) : null;
const integration = (name, callback) => test(name, { skip: !pool }, callback);

before(async () => {
  if (!pool) return;
  const sql = readFileSync(fileURLToPath(new URL(
    "../../spec/sql/postgres/001_idempotencykit_records.sql",
    import.meta.url)), "utf8");
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query(
      "SELECT pg_advisory_xact_lock(hashtext('idempotencykit_schema_001'))");
    await client.query(sql);
    await client.query(`
      CREATE TABLE IF NOT EXISTS idempotencykit_txn_orders_test (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scope_key_hash text NOT NULL,
        quantity integer NOT NULL
      )`);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
});
after(async () => {
  if (pool) await pool.end();
  assert.deepEqual(unexpectedPoolErrors, [],
    "Unexpected background pool errors should fail the test.");
});

const newKey = () => computeScopeKey({
  namespace: "transaction-test",
  operationId: "orders.create.v1",
  principalId: "user-" + randomUUID(),
  tenantId: "tenant-a",
  clientKey: "order-" + randomUUID(),
});
const fingerprint = quantity => computeRequestFingerprint({
  method: "POST",
  operationId: "orders.create.v1",
  path: "/orders",
  bodyJson: JSON.stringify({ quantity }),
});
const getCount = async (table, key) => {
  if (!["idempotencykit_txn_orders_test", "idempotencykit_records"].includes(table))
    throw new Error("Unexpected test table.");
  const result = await pool.query(
    `SELECT count(*) AS count FROM ` + table + ` WHERE scope_key_hash = $1`,
    [key],
  );
  return Number(result.rows[0].count);
};
const insertOrder = async (client, key, quantity) => {
  const result = await client.query(
    `INSERT INTO idempotencykit_txn_orders_test(scope_key_hash, quantity)
      VALUES ($1, $2) RETURNING id`, [key, quantity]);
  const id = result.rows[0].id;
  return {
    statusCode: 201,
    contentType: "application/json; charset=utf-8",
    body: Buffer.from(JSON.stringify({ id, quantity }), "utf8"),
    headers: { Location: "/orders/" + id },
  };
};

integration("business mutation and response commit atomically; same key replays", async () => {
  const key = newKey(), hash = fingerprint(2);
  let calls = 0;
  const first = await executor.execute(key, hash, async client => {
    calls++;
    return insertOrder(client, key, 2);
  }, 86_400_000);
  assert.equal(first.status, "executed");
  assert.equal(calls, 1);
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
  assert.equal(await getCount("idempotencykit_records", key), 1);

  const second = await new PostgresTransactionalExecutor(pool).execute(
    key, hash, async () => {
      calls++;
      throw new Error("Callback must never execute on replay.");
    }, 86_400_000);
  assert.equal(second.status, "replayed");
  assert.equal(second.response.statusCode, first.response.statusCode);
  assert.deepEqual(Buffer.from(second.response.body), Buffer.from(first.response.body));
  assert.equal(second.response.headers.location, first.response.headers.location);
  assert.equal(calls, 1);

  const mismatch = await executor.execute(key, fingerprint(3), async () => {
    throw new Error("Callback must never execute on mismatch.");
  }, 86_400_000);
  assert.equal(mismatch.status, "fingerprint_mismatch");
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
});

integration("callback throws after business insert -> both records rollback", async () => {
  const key = newKey(), hash = fingerprint(4);
  await assert.rejects(() => executor.execute(key, hash, async client => {
    await insertOrder(client, key, 4);
    throw new Error("Simulated handler failure after database mutation.");
  }, 86_400_000));
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
  assert.equal(await getCount("idempotencykit_records", key), 0);

  const retry = await executor.execute(key, hash,
    client => insertOrder(client, key, 4), 86_400_000);
  assert.equal(retry.status, "executed");
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
});

integration("invalid response fails before commit: no business effect or replay record", async () => {
  const key = newKey(), hash = fingerprint(5);
  await assert.rejects(() => executor.execute(key, hash, async client => {
    const response = await insertOrder(client, key, 5);
    return { ...response, headers: { "Set-Cookie": "secret=123" } };
  }, 86_400_000));
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
  assert.equal(await getCount("idempotencykit_records", key), 0);

  await assert.rejects(() => executor.execute(key, hash, async client => {
    const response = await insertOrder(client, key, 5);
    return { ...response, body: Buffer.from("not-json") };
  }, 86_400_000));
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
  assert.equal(await getCount("idempotencykit_records", key), 0);
});

integration("24 concurrent same-key calls commit one domain mutation", async () => {
  const key = newKey(), hash = fingerprint(6);
  let calls = 0;
  const concurrent = new PostgresTransactionalExecutor(pool, 5_000);
  const results = await Promise.all(Array.from({ length: 24 }, () =>
    concurrent.execute(key, hash, async client => {
      calls++;
      await new Promise(resolve => setTimeout(resolve, 100));
      return insertOrder(client, key, 6);
    }, 86_400_000)));
  assert.equal(results.filter(r => r.status === "executed").length, 1);
  assert.ok(results.every(r =>
    ["executed", "replayed", "in_progress"].includes(r.status)));
  assert.equal(calls, 1);
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
  assert.equal(await getCount("idempotencykit_records", key), 1);
  const replay = await executor.execute(key, hash, async () => {
    throw new Error("Must not reexecute after commit.");
  }, 86_400_000);
  assert.equal(replay.status, "replayed");
});

integration("pending transaction remains invisible; competing call times out safely", async () => {
  const key = newKey(), hash = fingerprint(9);
  let started;
  const startedPromise = new Promise(resolve => { started = resolve; });
  let unblock;
  const blocker = new Promise(resolve => { unblock = resolve; });

  const first = executor.execute(key, hash, async client => {
    const response = await insertOrder(client, key, 9);
    started();
    await blocker;
    return response;
  }, 86_400_000);
  await startedPromise;

  try {
    // PostgreSQL READ COMMITTED cannot observe uncommitted business or key rows.
    assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
    assert.equal(await getCount("idempotencykit_records", key), 0);
    const competing = await new PostgresTransactionalExecutor(pool, 50).execute(
      key, hash, async () => {
        throw new Error("An uncommitted key must not permit a second writer.");
      }, 86_400_000);
    assert.equal(competing.status, "in_progress");
  } finally {
    unblock();
  }
  assert.equal((await first).status, "executed");
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
  assert.equal((await executor.execute(key, hash, async () => {
    throw new Error("Committed result must replay.");
  }, 86_400_000)).status, "replayed");
});

integration("transactional and Standard-mode stores interoperate without reexecuting unknowns", async () => {
  const key = newKey(), hash = fingerprint(7);
  const claim = await store.tryClaim(key, hash, 60_000);
  assert.equal(claim.status, "acquired");
  const busy = await executor.execute(key, hash, async () => {
    throw new Error("Standard-mode owner must block a new transaction.");
  }, 86_400_000);
  assert.equal(busy.status, "in_progress");
  assert.equal(await store.tryMarkUncertain(key, hash, claim.ownerToken), true);
  const uncertain = await executor.execute(key, hash, async () => {
    throw new Error("Unknown business outcome must not be executed.");
  }, 86_400_000);
  assert.equal(uncertain.status, "uncertain");

  const completedKey = newKey();
  const done = await executor.execute(completedKey, hash,
    client => insertOrder(client, completedKey, 7), 86_400_000);
  assert.equal(done.status, "executed");
  const replay = await store.tryClaim(completedKey, hash, 30_000);
  assert.equal(replay.status, "completed");
  assert.deepEqual(Buffer.from(replay.response.body), Buffer.from(done.response.body));
});

integration("database backend termination before COMMIT rolls both writes back", async () => {
  const key = newKey(), hash = fingerprint(8);
  allowExpectedBackendTermination = true;
  await assert.rejects(() => executor.execute(key, hash, async client => {
    await insertOrder(client, key, 8);
    await client.query("SELECT pg_terminate_backend(pg_backend_pid())");
    throw new Error("Backend termination should have thrown.");
  }, 86_400_000));

  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
  assert.equal(await getCount("idempotencykit_records", key), 0);
  const retry = await executor.execute(key, hash,
    client => insertOrder(client, key, 8), 86_400_000);
  assert.equal(retry.status, "executed");
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
});

function startCrashWorker(phase, key, hash) {
  const worker = fork(
    fileURLToPath(new URL("./support/transactional-sigkill-worker.mjs", import.meta.url)),
    [phase, key, hash],
    {
      env: process.env,
      stdio: ["ignore", "ignore", "pipe", "ipc"],
    },
  );
  let stderr = "";
  worker.stderr?.on("data", chunk => { stderr += String(chunk); });
  const reached = new Promise((resolve, reject) => {
    const timeout = setTimeout(() => {
      reject(new Error("Transactional worker did not reach checkpoint: " + stderr));
    }, 10_000);
    worker.once("message", message => {
      clearTimeout(timeout);
      if (message?.phase === phase) resolve(message);
      else reject(new Error("Unexpected worker message: " + JSON.stringify(message)));
    });
    worker.once("error", error => {
      clearTimeout(timeout);
      reject(error);
    });
    worker.once("exit", (code, signal) => {
      clearTimeout(timeout);
      reject(new Error(
        "Worker exited before checkpoint (code " + code + ", signal " + signal + "): " + stderr));
    });
  });
  return { worker, reached };
}

async function killAndWait(worker) {
  if (worker.exitCode !== null || worker.signalCode !== null) return;
  const ended = new Promise(resolve => worker.once("exit", resolve));
  if (!worker.kill("SIGKILL")) throw new Error("Could not kill transaction test worker.");
  await ended;
}

async function waitForCount(table, key, expected) {
  for (let attempt = 0; attempt < 80; attempt++) {
    if (await getCount(table, key) === expected) return;
    await new Promise(resolve => setTimeout(resolve, 25));
  }
  assert.equal(await getCount(table, key), expected);
}

integration("SIGKILL worker BEFORE COMMIT rolls back order and record", async () => {
  const key = newKey(), hash = fingerprint(42);
  const { worker, reached } = startCrashWorker("before-commit", key, hash);
  try {
    await reached;
    // The worker inserted an order but has not committed either record.
    assert.equal(await getCount("idempotencykit_txn_orders_test", key), 0);
    assert.equal(await getCount("idempotencykit_records", key), 0);
  } finally {
    await killAndWait(worker);
  }

  await waitForCount("idempotencykit_txn_orders_test", key, 0);
  await waitForCount("idempotencykit_records", key, 0);

  const retry = await executor.execute(key, hash,
    client => insertOrder(client, key, 42), 86_400_000);
  assert.equal(retry.status, "executed");
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
  assert.equal(await getCount("idempotencykit_records", key), 1);
});

integration("SIGKILL worker AFTER COMMIT replays without reexecuting order", async () => {
  const key = newKey(), hash = fingerprint(42);
  const { worker, reached } = startCrashWorker("after-commit", key, hash);
  try {
    const checkpoint = await reached;
    assert.equal(checkpoint.status, "executed");
    assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
    assert.equal(await getCount("idempotencykit_records", key), 1);
  } finally {
    await killAndWait(worker);
  }

  const result = await executor.execute(key, hash, async () => {
    throw new Error("After committed SIGKILL, retry must replay, never reexecute.");
  }, 86_400_000);
  assert.equal(result.status, "replayed");
  assert.equal(JSON.parse(Buffer.from(result.response.body).toString()).quantity, 42);
  assert.equal(await getCount("idempotencykit_txn_orders_test", key), 1);
  assert.equal(await getCount("idempotencykit_records", key), 1);
});

